-- 부분 반품 이전에 걸려 있던 반품 요청을 «전량 요청» 으로 채운다 (2026-08-25, BACKLOG G-10).
--
-- ---------------------------------------------------------------- 🔴 왜 필요한가
--
-- V58 이 `return_requested_quantity` 를 **DEFAULT 0** 으로 넣었다. 새 행에는 그게 맞는 값이지만,
-- **이미 `RETURN_REQUESTED` 상태로 걸려 있던 주문**에는 틀렸다 — 그 요청은 «주문 전체를 반품해
-- 달라» 였는데(부분이라는 개념이 없던 시절이다) 새 코드는 «아무 품목도 안 골랐다» 로 읽는다.
--
-- 🔴 **증상**: 관리자가 그 주문의 「반품 승인」을 누르면 `ORDER-400RI`
--   («반품할 품목을 하나 이상 골라야 합니다») 로 거부된다. **고객은 요청해 놓고 영영 처리되지 않고,
--   관리자는 자기가 뭘 잘못 눌렀는지 알 수 없다.**
--
-- ⚠ **V58 을 고칠 수는 없다** — 이미 적용됐고 스크립트 수정은 체크섬 불일치다(README 규칙).
--   그래서 보정을 새 버전으로 낸다.
--
-- ⚠ **실측으로 찾았다**(2026-08-25). 테스트는 전부 초록이었다 — 테스트가 만드는 주문은 **새 코드로**
--   요청되기 때문이다. 🔴 **«마이그레이션 이전부터 그 상태로 있던 행»** 은 테스트가 만들 수 없는
--   모양이라, 운영 데이터를 세어 보기 전에는 안 보인다(WA §2-2 가 «기존 데이터 위반» 을 세라고
--   하는 이유가 이것인데, 그 검사는 «제약을 어기나» 만 봤지 «뜻이 맞나» 는 안 봤다).
--
-- ---------------------------------------------------------------- 🔴 왜 이 조건인가
--
-- «그 주문의 품목이 **전부** 0 인 경우» 로만 좁힌다. 한 품목이라도 0 이 아니면 그건 **새 방식으로
-- 고른 요청**이고, 0 인 품목은 고객이 **일부러 뺀** 것이다 — 거기까지 채우면
-- «안 고른 품목이 따라 반품되는» 바로 그 사고를 마이그레이션이 저지르게 된다
-- (`Order.rejectReturn` 이 요청 수량을 지우는 것과 같은 이유).
--
-- ⚠ 그래서 이 스크립트는 **다시 돌려도 안전하다**(같은 조건이 두 번째엔 성립하지 않는다).
--
-- ---------------------------------------------------------------- ⚠ 배포 순서가 이걸 완전하게 만든다
--
-- 구 jar 가 도는 동안에도 «옛 방식의 반품 요청» 이 새로 생길 수 있다(그 jar 는 사유만 받는다).
-- 🔴 **그래도 새는 것이 없다** — Flyway 는 **새 jar 가 뜰 때** 돌고, 그 시점엔 구 jar 가 이미
-- 멈춰 있다(`deploy-backend.sh`: 빌드 → 서비스 재시작). 즉 이 스크립트가 보는 스냅샷에는
-- 구 jar 가 만든 마지막 요청까지 들어 있다.
--
-- ⚠ 적용 시점 실측: 대상 **1건**(`20260724-0246`, 품목 1개 · 수량 1). 부분 취소·부분 반품이 섞인
--   주문은 없었다(`cancelled_quantity`·`returned_quantity` 가 둘 다 0).

UPDATE order_item i
   SET i.return_requested_quantity = i.quantity - i.cancelled_quantity - i.returned_quantity
 WHERE EXISTS (SELECT 1 FROM orders o
                WHERE o.id = i.order_id
                  AND o.status = 'RETURN_REQUESTED')
   AND NOT EXISTS (SELECT 1 FROM order_item x
                    WHERE x.order_id = i.order_id
                      AND x.return_requested_quantity > 0)
   AND i.quantity - i.cancelled_quantity - i.returned_quantity > 0;
