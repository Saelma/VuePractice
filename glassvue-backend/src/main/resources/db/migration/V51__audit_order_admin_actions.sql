-- 관리자 주문 조작 넷(발송·배송완료·반품 승인·반품 거절)을 감사 원장에 남긴다
-- (2026-08-14, BACKLOG 「감사 대상 확대」 — V50 과 같은 날의 두 번째 확장)
--
-- ⚠ **원장에 남는 관리자 주문 조작은 「대행 취소」 하나뿐이었다**(V43). 나머지 넷은 아무 데도 안 남았다.
--
--   | 조작        | 무슨 일이 일어나나                       | 주문에 남는 것            | 「누가」 |
--   |-------------|------------------------------------------|---------------------------|---------|
--   | 발송        | 상태 + 택배사·송장                       | shipped_at·ship_*         | ❌ 없다 |
--   | 배송완료    | **적립금이 나간다**(earnOnDelivery)      | delivered_at              | ❌ 없다 |
--   | 반품 승인   | 재고 복원 + **환불** + 쿠폰 복구         | returned_at               | ❌ 없다 |
--   | 반품 거절   | 상태를 DELIVERED 로 되돌린다             | return_rejected_reason    | ❌ 없다 |
--   | 대행 취소   | 재고·적립금·쿠폰 되돌림                  | cancelled_by(_name)       | ✅ V43  |
--
--   🔴 **넷 다 「언제」는 남고 「누가」는 안 남았다.** 행위자 컬럼을 가진 것이 취소 하나이고,
--   그게 바로 감사도 함께 붙은 자리다 — 둘이 같이 빠져 있었던 것이다.
--   돈이 나가는 조작(배송완료 적립·반품 환불)인데도 «누가 승인했나» 를 물을 방법이 없었다.
--
-- ---------------------------------------------------------------- 착수 전 결정 (사용자와 확정)
--
-- **어디까지 남기나 → 넷 전부**(2026-08-14).
--   ⚠ **대가를 알고 골랐다**: 발송·배송완료는 **모든 주문**이 거치므로 원장이 주문 수에 비례해 큰다
--     (지금 63주문 → 최대 126행). F-2(알림이 쌓인다)와 같은 압력이지만 **대응은 다르다** —
--     알림은 지워도 되는 통지이고 **원장은 append-only 가 존재 이유**다. 커지면 조회를 좁힐 일이지
--     지울 일이 아니다.
--   안 고른 것: 「반품 승인·거절만」(판정만 남긴다 — 원장이 안 커지지만 «누가 발송 처리했나» 는 여전히
--     못 읽는다) · 「돈이 오가는 것만」(발송 제외 — 기준은 또렷하나 흐름이 끊겨 읽힌다).
--
-- **대상은 주문자(회원)** — V43 과 같은 모양이다. 주문번호는 detail 에 넣는다.
--   ⚠ V50(상품)이 부딪힌 «대상에 회원이 없다» 가 여기서는 안 생긴다 → **target_type 논의도 안 생긴다.**
--
-- **detail 에는 그 조작이 «무엇을 움직였는지» 를 적는다** — 발송은 택배사·송장,
--   배송완료는 **나간 적립금**, 반품 승인은 **환불액**, 거절은 **사유**.
--   ⚠ 거절 사유는 return_rejected_reason 에도 있지만 **그건 현재 상태**다 — 재요청이 오면
--     requestReturn 이 null 로 지운다. 원장 쪽이 이력이다(같은 정보의 중복이 아니다).
--
-- ---------------------------------------------------------------- 안 남기는 것 · 백필
--
-- ❌ **본인 취소·본인 반품 요청**은 관리자 조작이 아니다 — 원장은 «관리자가 무엇을 했나» 다.
-- ❌ **결제(pay)** 도 회원 본인이다.
-- 🔴 **과거 조작은 백필하지 않는다** — 시각(shipped_at 등)은 있어도 **행위자를 모른다.**
--   원장은 오늘부터 시작한다(V44 가 리뷰 숨김에서, V50 이 상품 삭제에서 한 판단과 같다).
--
-- ⚠ **멱등 논의가 여기서는 안 생긴다**(V50 과 다른 점). 넷 다 상태 가드가 **예외를 던진다**
--   (isShippable·isDeliverable·isReturnPending) — 조용히 통과하는 경로가 없어
--   «호출됐지만 아무 일도 안 일어난» 줄이 생길 수 없다. V50 은 softDelete 가 조용히 통과해서
--   boolean 을 돌려주게 고쳐야 했다.
--
-- ⚠ **넓히는 방향이라 구 jar 는 영향받지 않는다**(구 jar 는 이 값들을 아예 만들지 않는다).
-- ⚠ 적용된 스크립트는 고치지 않는다 — 체크섬이 어긋나면 기동이 통째로 막힌다(V45 주석의 사고).

