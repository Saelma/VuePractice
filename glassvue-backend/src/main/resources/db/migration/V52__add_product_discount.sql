-- 기간 할인(타임세일) (2026-08-19, BACKLOG G-5)
--
-- ⚠ **지금 할인에는 기간 개념이 없다.** 관리자가 `product.list_price` 를 손으로 넣고 손으로 되돌리는
--   방식이라 *"이번 주말만 20%"* 를 하려면 **주말에 사람이 앉아 있어야 한다.**
--
-- ---------------------------------------------------------------- 왜 컬럼이 아니라 테이블인가
--
-- 🔴 **`product` 에 `sale_rate`·`sale_until` 컬럼을 더하는 안은 버렸다.** 이유가 둘이다:
--   ① **다음 세일을 미리 등록할 수 없다.** 컬럼이 한 벌이면 «지금 세일» 만 담긴다 — *"이번 주말 20%,
--      다음 달 초 10%"* 를 미리 넣어 두는 것이 이 기능의 목적인데 그걸 못 한다.
--   ② **끝난 세일이 흔적 없이 사라진다.** 덮어쓰면 «지난주에 얼마에 팔았나» 가 남지 않는다.
--      ⚠ 주문 쪽은 안전하다(B-7 이 정가·판매가를 주문에 복사한다) — 하지만 그건 «팔린 것» 의 기록이지
--      «걸었던 세일» 의 기록이 아니다. 안 팔린 세일은 주문에 안 남는다.
--
-- ⚠ **V48(`deleted_at`)이 컬럼으로 간 것과 갈리는 지점이 여기다.** 삭제 대기는 상품당 **하나뿐인
--   상태**라 컬럼이 맞았고, 할인은 **여러 개가 줄지어 서는 일정**이라 행이 맞다.
--
-- ---------------------------------------------------------------- 왜 정률(%)인가 (2026-08-19, 사용자 결정)
--
-- 정액(원)이 아니라 **비율**이다. 옵션 가격차(`product_variant.price_delta`)와 얽히기 때문이다 —
-- 정액이면 싼 옵션과 비싼 옵션에 **같은 액수**가 붙어 체감 할인율이 제각각이 된다("L +2000" 에도
-- 같은 2,000원이 빠지면 기본 옵션은 반값인데 L 은 조금만 싸진다).
-- ⚠ **적용 순서를 여기 못 박는다**: `(product.price + price_delta) × (100 - rate) / 100`.
--   즉 **가격차를 더한 뒤에 할인율을 적용**한다 — 모든 옵션이 같은 비율로 싸진다.
--   🔴 **실측(2026-08-19): `price_delta` 가 0 이 아닌 옵션이 10개 중 0건**이라, 이 순서는 지금
--   데이터로는 검증되지 않는다(순서를 뒤집어도 결과가 같다). 검증 표본은 **가격차가 0이 아닌 옵션을
--   일부러 만들어** 밟는다 — 안 그러면 «밟았는데 맞았다» 가 아니라 «안 밟아서 안 틀렸다» 다(WA §3-3).
--
-- ⚠ **원 단위 반올림은 앱이 한 자리에서 한다**(`ProductDiscount.applyTo`). SQL 과 Java 가 각자
--   반올림하면 **목록의 가격과 장바구니의 가격이 1원 어긋난다** — 눈에 잘 안 띄고 결제에서 터진다.
--   → 쿼리 쪽 CASE 도 **같은 식(ROUND)** 을 쓴다.
--
-- ---------------------------------------------------------------- 🔴 겹침은 DB 가 못 막는다 — 앱이 유일한 방어
--
-- ⚠ **G-8(V49)에서 겪은 것과 같은 자리다.** Oracle 유니크 인덱스로는 «기간이 겹치는 행» 을 막을 수 없다
--   (유니크는 값의 동일성만 본다). 한 상품에 «8/20~8/25 20%» 와 «8/23~8/28 30%» 가 동시에 있으면
--   **8/23~8/25 에 어느 것이 맞는지 DB 는 답하지 못한다.**
--   → **앱이 등록·수정에서 막고, 그 규칙은 테스트가 못 박는다**(DB 가 아니라 테스트가 유일한 방어라서).
--   → 🔴 **그래도 뚫렸을 때 목록이 죽지 않게** 조회는 `Optional` 이 아니라 **`List` 로 받는다**
--      (G-8 에서 «열린 이벤트 둘» 이 홈 전체를 500 으로 만들 뻔했다). 뚫리면 **할인율이 가장 높은 것**을
--      적용하고 경고 로그를 남긴다 — 고객에게 유리한 쪽이 사고가 덜 난다.
--
-- ---------------------------------------------------------------- CASCADE · 백필 · 구 jar
--
-- ⚠ **상품이 지워지면 할인도 함께 지운다**(`product_variant`·`stock_history` 와 같은 판단).
--   유예(F-7) 안에 복구하면 할인도 함께 돌아온다. 유예가 지나 배치가 지우면 함께 사라지는데,
--   **그때 이미 팔린 주문의 금액은 안 변한다**(B-7 스냅샷). 그 토대가 있어서 CASCADE 가 안전하다.
-- ⚠ **백필 없음** — 새 테이블이다. 실측(2026-08-19): 상품 10건(살아 있는 것 6) 중 `list_price` 가
--   있는 것 3건이고 **정가 ≤ 판매가인 잘못된 행은 0건**이다. 기존 정가는 건드리지 않는다 —
--   🔴 **정가와 세일은 다른 것이다**(정가는 «원래 이 값어치», 세일은 «이 기간만 싸게»).
-- ⚠ 순수 추가라 구 jar 는 영향받지 않는다 — 이 테이블을 안 읽으니 세일 전 가격으로 계속 판다.
--   **배포 전까지 세일이 적용되지 않을 뿐 금액이 어긋나지는 않는다.**

CREATE TABLE product_discount (
    id         RAW(16)             NOT NULL,
    -- catalog 도메인 **안**이라 진짜 FK 를 건다(product_variant 와 같은 판단).
    product_id RAW(16)             NOT NULL,
    -- 할인율 %. 1~99 만 허용한다 — 0 은 «할인 없음» 이라 행을 만들 이유가 없고(그런 행은 화면에
    -- 「세일 중」으로 뜨면서 가격이 그대로라 고장으로 읽힌다), 100 은 공짜라 주문·결제·적립 계산이
    -- 전부 0원 경로로 들어간다. 필요해지면 그때 연다.
    rate       NUMBER(3,0)         NOT NULL
               CONSTRAINT ck_product_discount_rate CHECK (rate BETWEEN 1 AND 99),
    starts_at  TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    ends_at    TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(9) WITH TIME ZONE,
    updated_at TIMESTAMP(9) WITH TIME ZONE,
    PRIMARY KEY (id),
    -- 「시작이 끝보다 뒤」인 행은 어느 순간에도 유효하지 않아 **조용히 아무 일도 안 한다** —
    -- 관리자는 세일을 걸었다고 믿고 가격은 그대로다. 앱에서도 막지만 DB 에서도 막는다
    -- (⚠ 같은 시각은 허용하지 않는다: 길이 0 인 세일도 아무 일도 안 하는 것은 같다).
    CONSTRAINT ck_product_discount_period CHECK (ends_at > starts_at),
    CONSTRAINT fk_product_discount_product FOREIGN KEY (product_id)
        REFERENCES product (id) ON DELETE CASCADE
);

-- ⚠ **FK 인덱스는 성능이 아니라 잠금 때문에 만든다.** Oracle 은 인덱스 없는 자식 FK 가 있으면
--   부모 행 삭제 시 **자식 테이블 전체에 락**을 건다. 상품 삭제는 `ProductPurgeScheduler` 가
--   한 건씩 도는 경로라(F-7) 그때 다른 요청이 이 테이블을 못 쓰게 된다.
-- ⚠ 목록 조회의 «지금 유효한 할인» 도 이 인덱스로 상품별 진입한다(행이 적어 기간은 필터로 충분하다).
CREATE INDEX ix_product_discount_product ON product_discount (product_id);

COMMENT ON TABLE product_discount IS
    '상품 기간 할인(타임세일). 한 상품에 여러 행이 줄지어 설 수 있고, 기간이 겹치지 않게 하는 것은 앱의 책임이다 (2026-08-19, G-5)';

COMMENT ON COLUMN product_discount.rate IS
    '할인율 %(1~99). 실제 판매가 = ROUND((product.price + product_variant.price_delta) * (100 - rate) / 100) (2026-08-19, G-5)';

COMMENT ON COLUMN product_discount.starts_at IS
    '세일 시작 시각(포함). 이 시각 이후부터 할인가로 팔린다 (2026-08-19, G-5)';

COMMENT ON COLUMN product_discount.ends_at IS
    '세일 종료 시각(배타). 이 시각이 되면 원래 판매가로 돌아온다 — 23:59:59 로 두면 그 사이 0.5초 결제가 원가로 나가고 초 미만은 눈에 안 보인다 (2026-08-19, G-5. B-26 의 날짜 경계와 같은 판단)';
