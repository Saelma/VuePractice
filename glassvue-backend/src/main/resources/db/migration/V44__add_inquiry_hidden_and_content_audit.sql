-- 문의 숨김 + 콘텐츠 조치 감사 (2026-08-10, 백로그 B-18 잔여)
--
-- ⚠ **부적절한 문의를 내릴 방법이 없었다.** 리뷰는 2026-08-04(V41)에 숨김을 얻었는데 문의는
--   그때 «G-3 과 함께 볼 때 다시 판단한다» 로 미뤄졌고, 08-07 재판단에서도 *"G-3 이 푸는 것은
--   «답할 경로가 없다» 이고 숨김은 다른 문제"* 라 또 미뤄졌다. 그 사이 문의 작성 경로만 둘로 늘었다.
--
-- ---------------------------------------------------------------- 이 컬럼이 닿는 자리는 셋
--
-- ① **상품 문의 목록**(findByProduct) — 빠진다.
-- ② **내 문의**(findByAuthor) — 빠진다. 🔴 **작성자 본인에게도**(2026-08-10 결정).
--    리뷰가 같은 결정을 했으므로 둘이 같은 규칙을 갖는다. 갈라 두면 «어느 목록에서 빠지나» 를
--    매번 되짚어야 하고, 조회 경로가 둘이라 **한쪽만 고치는 사고**가 난다.
--    대가: 작성자는 자기 글이 소리 없이 사라졌다고 느낀다 — CS 로 물어보면 그때 설명한다.
-- ③ **관리자 목록**(findForAdmin) — 🔴 **보인다**(필터로 가른다). 여기만 반대다.
--    안 보이면 **숨긴 것을 되돌릴 방법이 없다**.
--
-- ⚠ **리뷰(V41)에 있던 「상품당 1회 제한」 같은 자리가 여기엔 없다.** 리뷰는 숨겨도 그 제한에는
--   그대로 세야 했지만(안 그러면 숨기자마자 새로 써서 숨김이 무의미해진다), 문의는 **개수 제한도
--   집계도 없다.** 그래서 «반대로 다뤄야 하는 자리» 가 관리자 목록 하나뿐이다.
--
-- ---------------------------------------------------------------- 컬럼
--
-- DEFAULT 0 으로 **백필한다** — 기존 문의는 **실제로 숨겨진 적이 없으므로 0 이 사실**이다
-- (V41 review.hidden · V34 email_verified 와 같다). "모르는 값" 이 아니라 "아니다" 라서
-- NOT NULL 로 둘 수 있고, 그래야 조회 조건에 NULL 갈래가 안 생긴다.

ALTER TABLE inquiry ADD hidden NUMBER(1) DEFAULT 0 NOT NULL;

ALTER TABLE inquiry ADD CONSTRAINT ck_inquiry_hidden CHECK (hidden IN (0, 1));

COMMENT ON COLUMN inquiry.hidden IS
    '관리자 숨김(1=숨김). 상품 문의 목록·내 문의에서 빠지고(작성자 본인에게도) 관리자 목록에는 남는다';

-- 인덱스는 두지 않는다. V41 과 같은 판단이다 — 값이 둘뿐이라 선택도가 낮고, 조회 경로에는
-- 이미 product_id·author_id 조건이 붙는다. 관리자 목록(전체)은 건수가 작고 페이징이 있다.

-- ---------------------------------------------------------------- 감사 enum CHECK 확장
--
-- 🔴 **B-18(2026-08-04)은 감사를 «못 붙인다» 며 접었다.** 이유는 *"AdminActionEvent 가 회원 대상
--   설계라(targetId=대상 회원) 리뷰에 안 맞는다"* 였는데 **그 전제가 틀렸다** — 리뷰에는 authorId,
--   문의에는 authorId 가 있다. 같은 날 V43 이 주문 취소를 «대상=주문자» 로 붙이면서 드러났다:
--   갈리는 기준은 **도메인이 아니라 «대상에 회원이 있느냐»** 다.
--
-- 🔴 **리뷰 숨김은 이미 배포된 기능이라 과거 조치는 감사에 없다.** 백필할 출처가 없다 —
--   review.hidden 은 **현재 상태만** 갖고 «누가 언제» 를 모른다. 원장이 오늘부터 시작한다는 뜻이고,
--   이건 "모르는 값" 이라 **지어내지 않는다**(V37 이 동의 시각을 백필하지 않은 것과 같은 판단).
--
-- ⚠ 넓히는 방향이라 구 jar 는 영향받지 않는다(구 jar 는 이 값들을 아예 만들지 않는다).

ALTER TABLE admin_audit_log DROP CONSTRAINT ck_admin_audit_action;

ALTER TABLE admin_audit_log ADD CONSTRAINT ck_admin_audit_action
    CHECK (action IN ('MEMBER_SUSPEND', 'MEMBER_UNSUSPEND', 'MEMBER_ROLE_CHANGE', 'MEMBER_DELETE',
                      'ORDER_CANCEL',
                      'REVIEW_HIDE', 'REVIEW_UNHIDE', 'INQUIRY_HIDE', 'INQUIRY_UNHIDE'));
