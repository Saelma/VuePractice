-- 이벤트 쿠폰 발급 창 + 중복 발급 금지 (2026-08-13, BACKLOG G-8)
--
-- 「그 날 접속해서 「받기」를 누른 사람에게 한 장」을 만드는 자리다. 컬럼 하나와 인덱스 하나로 끝난다.
--
-- ---------------------------------------------------------------- 왜 issue_until 인가
--
-- 🔴 **「언제 받을 수 있나」와 「언제까지 쓸 수 있나」가 지금 같은 값이었다**(2026-08-12 실측).
--   `coupon` 의 기간 컬럼은 `valid_from`·`valid_until` 뿐이고 그 값을 `redeem` 이 사용 가능 판정에
--   쓴다(`CouponService.redeem` → COUPON_EXPIRED). 이벤트 창을 그 값으로 쓰면
--   «8/15 하루 이벤트» 쿠폰이 **그 날 자정에 만료된다** — 받자마자 못 쓴다.
--
--   | 무엇                        | 컬럼                    | 값              |
--   |-----------------------------|-------------------------|-----------------|
--   | 이벤트 날(발급 시작=사용 시작) | `valid_from`(기존)      | 그 날 00:00     |
--   | **발급 마감**                | **`issue_until`**(신설) | 그 날 23:59     |
--   | 사용 마감                    | `valid_until`(기존)     | 한 달 뒤        |
--
-- ⚠ **`issue_from` 은 두지 않는다**(2026-08-12, 사용자 결정). 발급 시작과 사용 시작이 항상 같은 값이면
--   `valid_from` 의 복사본일 뿐이다. *"미리 받아 두고 다음 달부터 쓰세요"* 가 필요해지면 그때 더한다
--   (**null = `valid_from` 과 같다** 로 읽으면 백필이 없다).
--
-- ⚠ **`TIMESTAMP(9) WITH TIME ZONE`** 이다. plain `TIMESTAMP` 는 validate 를 통과하고 **읽을 때
--   ORA-18716** 이 난다(V26 사고, V48 주석과 같은 이유).
--
-- ---------------------------------------------------------------- NULL 의 뜻 · 백필
--
-- ⚠ **NULL = 이벤트 쿠폰이 아니다(상시 쿠폰).** 별도의 boolean 플래그를 두지 않는다 —
--   `welcome`(V36)은 날짜만으로 «어느 것이 가입 쿠폰인지» 를 알 수 없어 플래그가 필요했지만,
--   이벤트 쿠폰은 **발급 마감일이 곧 정의**다. 플래그를 따로 두면 «켜졌는데 날짜가 없다» 는
--   모순 상태가 생기고 그걸 앱이 다시 막아야 한다.
-- ⚠ **백필 없음** — 기존 쿠폰 5건(2026-08-13 실측)은 전부 상시라 NULL 이 맞는 값이다.
--   G-2 의 *"지정 안 함 = 기능 꺼짐"* 과 같은 방식이다.

ALTER TABLE coupon ADD issue_until TIMESTAMP(9) WITH TIME ZONE;

COMMENT ON COLUMN coupon.issue_until IS
    '이벤트 쿠폰의 발급 마감 시각. NULL 이면 이벤트가 아닌 상시 쿠폰이다. 사용 마감은 valid_until 이며 보통 더 뒤다 (2026-08-13, G-8)';

-- ---------------------------------------------------------------- 중복 발급은 DB 가 막는다
--
-- 🔴 **앱 가드만으로는 동시 요청에 뚫린다** — 탭 두 개가 같은 순간 «아직 안 받았다» 를 읽으면
--   둘 다 발급된다. 「받기」는 사람이 연타할 수 있는 버튼이라 이 경로가 실제로 열린다.
--   화면의 연타 잠금도, 서비스의 사전 확인도 **경합을 좁힐 뿐 닫지는 못한다.** DB 가 최종 방어다.
--
-- ⚠ **이 인덱스는 이벤트 쿠폰만이 아니라 전체에 걸린다** — 즉 **「회원당 같은 쿠폰 1장」이
--   오늘부터 전역 규칙**이다(2026-08-13, 사용자 결정).
--   🔴 **이게 기존 동작을 바꾼다**: `CouponService.issue`(관리자 발급)의 주석은
--   *"같은 쿠폰을 여러 장 주는 것도 허용한다(이벤트 재발급 등)"* 였고, 실제로 허용하고 있었다.
--   이벤트 쿠폰만 막는 안(발급 경로 플래그 + 함수기반 유니크)도 있었지만, 컬럼을 하나 더 두고
--   같은 사실을 두 곳에 적는 대신 **규칙 자체를 하나로** 정했다.
--   → 관리자 발급은 이제 사전 확인 후 **4xx** 로 거절한다(같은 커밋의 `COUPON_ALREADY_ISSUED`).
--
-- ---------------------------------------------------------------- 인덱스 전에 기존 중복부터 (WA §2-5)
--
-- 🔴 **실측(2026-08-13): 중복이 이미 1쌍 있었다.** `김기현팀` 의 「가입 쿠폰 10000원」 두 장 —
--   둘 다 08-11 03:15, 08-11 쿠폰 복구 검증(§8)의 잔재로 보인다. 그냥 인덱스를 걸었으면
--   **마이그레이션이 ORA-01452 로 실패**했다. 2026-07-21 에 닉네임 UNIQUE(V6)를 넣다가 운영 구 jar 가
--   500 을 낸 것과 같은 자리다 — *"재발 방지와 기존 잔재 정리는 별개 작업"*(WA §2-5).
--
-- ⚠ **미사용 행만 지운다.** 사용한 발급쿠폰은 주문이 `member_coupon_id` 로 스냅샷하고 있어서
--   (V46) 지우면 **취소 시 쿠폰 복구가 대상을 잃는다**(`CouponService.restore` 가 경고만 남기고 넘어간다).
--   → 한 쌍이 **둘 다 사용됨**이면 여기서 아무것도 안 지워지고 **아래 인덱스 생성이 실패한다.**
--   그건 사고가 아니라 **의도된 정지**다 — 그 경우는 사람이 어느 주문을 살릴지 정해야 한다.
-- ⚠ 정렬이 «사용된 것 먼저» 인 이유가 그것이다: 남길 한 장을 고를 때 **주문이 가리키는 행을 우선**한다.

DELETE FROM member_coupon
WHERE used_at IS NULL
  AND rowid IN (
      SELECT rid FROM (
          SELECT rowid AS rid,
                 ROW_NUMBER() OVER (
                     PARTITION BY member_id, coupon_id
                     ORDER BY CASE WHEN used_at IS NULL THEN 1 ELSE 0 END, created_at, rowid) AS rn
          FROM member_coupon)
      WHERE rn > 1);

CREATE UNIQUE INDEX ux_member_coupon_once ON member_coupon (member_id, coupon_id);
