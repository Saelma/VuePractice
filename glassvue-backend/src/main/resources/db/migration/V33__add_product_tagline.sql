-- 상품 한 줄 태그라인 (2026-07-29, DESIGN.md §2 「8fter」 ②)
--
-- 목록 카드가 이름·가격·별점만 보여줘서 **무엇이 좋은 상품인지 목록에서 안 읽힌다.**
-- 카드에 얹을 짧은 설명("안 입은 듯한 무압박" 류)을 담을 자리를 만든다.
--
-- ⚠ **description 을 잘라 쓰지 않는 이유**: 설명은 문단이라 앞 N자를 자르면 문장이 중간에 끊긴다.
--    "카드에 보여줄 한 줄"은 상세 설명과 **목적이 다른 글**이라 별도 필드가 맞다.
--
-- ⚠ 이 마이그레이션은 **순수 추가 + nullable** 이라 구 jar 에 무해하다(WORKING-AGREEMENTS §5).
--    기존 상품은 전부 NULL 이고, 화면은 NULL 을 "태그라인 없음"으로 읽어 그 줄을 통째로 감춘다.
--    백필하지 않는다 — 채울 값이 없다(사람이 쓰는 카피이지 파생 데이터가 아니다).
--
-- ⚠ VARCHAR2 는 **CHAR semantics**(이 DB 의 NLS_LENGTH_SEMANTICS 는 BYTE — WA §2-2-1).
--    100자로 잡은 이유: 카드 한 줄에 들어가야 하므로 길면 어차피 잘린다. 상품명(200)보다 짧게 둬
--    "여기에 설명을 쓰지 말라"는 신호를 길이로 준다.

ALTER TABLE product ADD tagline VARCHAR2(100 CHAR);
