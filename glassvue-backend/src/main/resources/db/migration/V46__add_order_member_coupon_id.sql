-- 취소·반품 시 쿠폰 복구 (2026-08-11, 08-10 §16-4 3번)
--
-- ⚠ **취소해도 쿠폰이 안 돌아오고 있었다.** `OrderService.applyCancellation` 은
--   재고 복원 → 적립금 환불 → 알림까지 하는데 **쿠폰 줄이 없다**(반품 승인도 같다).
--   그리고 `CouponService` 에는 되돌리는 메서드가 **아예 없었다** — `MemberCoupon.use()` 는 있고
--   restore 는 없다. 즉 호출을 빠뜨린 게 아니라 «되돌린다» 는 개념이 만들어진 적이 없다.
--
-- ---------------------------------------------------------------- 왜 컬럼이 필요한가
--
-- 🔴 **고치려 해도 어느 쿠폰이었는지 모른다.** 주문은 쿠폰의 **이름과 금액만** 스냅샷한다
--   (coupon_name·coupon_discount, V-초기). 적립금은 used_point 라는 **금액만으로** 되돌릴 수 있지만
--   (얼마를 돌려줄지가 곧 답이다), 쿠폰은 **어느 장인지**를 알아야 그 행의 used_at 을 지운다.
--   같은 회원이 같은 쿠폰을 여러 장 받을 수 있어(CouponService.issue 가 허용) 이름으로는 못 찾는다.
--
-- ⚠ 2026-08-07 에 적립금 환불을 고칠 때 쿠폰은 «표에 행조차 없었다» 고 08-10 §16-4 가 적었는데,
--   실제로는 **행이 있었어도 그날 못 고쳤을** 자리다 — 마이그레이션이 먼저 필요했다.
--
-- ---------------------------------------------------------------- 왜 스냅샷이 아니라 id 인가
--
-- cancelled_by(V43)·couponName 은 «대상이 사라져도 읽혀야 하는 값» 이라 스냅샷을 떴다.
-- 이건 반대다 — **읽으려는 게 아니라 되돌리려는 것**이라, 그 행을 가리키는 값이어야 한다.
-- 이름은 이미 coupon_name 에 있으니 화면은 그쪽을 계속 쓴다(이 컬럼은 화면에 안 나간다).
--
-- ⚠ FK 를 걸지 않는다. 회원이 탈퇴하면 member_coupon 이 통째로 지워지는데
--   (CouponService.deleteAllForMember, F-1) FK 가 있으면 **주문이 그 삭제를 막는다.**
--   과거 주문은 남기기로 한 결정(주문자 닉네임을 스냅샷하는 이유)과 정면으로 부딪힌다.
--   → 가리키는 행이 없어지면 복구가 «조용히 안 되는» 것이 맞다(그때 고객은 이미 탈퇴했다).
--
-- ---------------------------------------------------------------- NULL 의 뜻
--
-- ⚠ **NULL = 쿠폰을 안 썼거나, 이 컬럼이 생기기 전의 주문이다.** 둘을 구분하려면 coupon_discount 를
--   함께 본다(> 0 인데 이 값이 NULL 이면 «옛 주문»).
-- ⚠ **백필하지 않는다** — 어느 장이었는지 알 방법이 없다. 짐작으로 채우면
--   **엉뚱한 사람의 쿠폰이 되살아난다**(V37 이 동의 시각을 백필하지 않은 것과 같은 판단:
--   NULL 은 정직하고, 지어낸 값은 근거로 쓰이는 순간 틀린 결정을 만든다).
--   실측(2026-08-11): 쿠폰을 쓴 주문은 **1건**(20260728-0478, DELIVERED, 탈퇴 회원)이고
--   그 회원의 member_coupon 은 탈퇴 정리로 이미 지워졌다 — 백필할 대상 자체가 없다.
--
-- ⚠ 구 jar 는 이 컬럼을 모른 채 계속 INSERT 한다(nullable 이라 문제없다) — 순수 추가라
--   WA §5 의 「구 jar 동작을 바꾸는 제약」에 해당하지 않는다.

ALTER TABLE orders ADD member_coupon_id RAW(16);

COMMENT ON COLUMN orders.member_coupon_id IS
    '사용한 발급쿠폰 id — 취소·반품 시 되돌릴 대상. NULL 이면 미사용이거나 V46 이전 주문 (2026-08-11)';

-- 인덱스는 두지 않는다. 이 값으로 주문을 찾는 화면이 없고, 복구는 주문에서 쿠폰 방향으로만 간다
-- (orders 행을 이미 손에 쥔 상태에서 member_coupon 을 PK 로 연다). V43 과 같은 판단.
