-- `admin_audit_log.target_type` 의 길이 semantics 를 BYTE → CHAR 로 바로잡는다 (2026-08-20)
--
-- 🔴 **V53 이 WORKING-AGREEMENTS §2-2-1 을 어겼다** — *"마이그레이션에 VARCHAR2 를 쓸 때는
--   예외 없이 CHAR 를 붙인다"*. `VARCHAR2(20)` 으로 적어서 이 DB 의 기본값(`NLS_LENGTH_SEMANTICS=BYTE`)
--   을 그대로 탔다.
--
--   실측(2026-08-20, V53 적용 직후):
--
--   | 컬럼          | char_used | 길이 |
--   |---------------|-----------|------|
--   | `action`      | **C**     | 20   |  ← V32 는 `VARCHAR2(20 CHAR)` 로 제대로 썼다
--   | `target_login`| **C**     | 50   |
--   | `target_type` | 🔴 **B**  | 20   |  ← 이것만 어긋났다
--
-- ---------------------------------------------------------------- 왜 «지금은 안 아픈데» 고치나
--
-- ⚠ **값이 ASCII 라 지금은 아무 일도 안 일어난다** — `MEMBER`·`PRODUCT`·`COUPON` 은 바이트 수와
--   글자 수가 같다. 그래서 이건 **버그가 아니라 어긋남**이다.
-- 🔴 **그래도 고치는 이유**: 7/21 사고가 정확히 이 모양이었다. `member.nickname`(50 CHAR)을 복사해
--   넣는 `orders.buyer_nickname` 이 50 **BYTE** 였고, **그런 회원이 아직 없어서 안 터졌을 뿐**이었다.
--   «지금 값으로는 문제없다» 는 «앞으로도 문제없다» 가 아니다.
-- ⚠ 그리고 **같은 표 안에서 열마다 규칙이 다르면** 다음 사람이 어느 쪽을 따라야 할지 모른다.
--
-- ---------------------------------------------------------------- 왜 V53 을 고치지 않고 새 파일인가
--
-- 🔴 **V53 은 이미 적용됐다** — 통합 테스트가 도는 순간 Flyway 가 공유 espdb 에 적용한다(WA §5).
--   적용된 스크립트를 고치면 **체크섬이 어긋나 기동이 통째로 막힌다**(V45 주석의 사고).
--   → 어긋남은 **되돌리는 것이 아니라 다음 마이그레이션으로 덮는다.**
--
-- ⚠ **넓히는 방향이라 안전하다**(20 BYTE ⊂ 20 CHAR). 구 jar 도 영향받지 않는다 —
--   저장하는 값이 그대로고 컬럼이 사라지지도 좁아지지도 않는다.
-- ⚠ NOT NULL 과 CHECK 제약은 MODIFY 로 안 건드려진다(길이 semantics 만 바꾼다).

ALTER TABLE admin_audit_log MODIFY target_type VARCHAR2(20 CHAR);
