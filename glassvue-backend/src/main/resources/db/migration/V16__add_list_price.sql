-- 정가(할인 전 가격) (2026-07-23)
--
-- `product.price` 하나뿐이라 "20% 할인" 을 표현할 방법이 없었다.
--
-- ⚠ **`price` 의 의미를 바꾸지 않는다.** `price` 는 계속 **실제 판매가**다 —
--    장바구니 합계·주문 금액·배송비 무료 기준이 전부 이 값을 쓴다.
--    여기를 정가로 바꾸고 할인가를 따로 두면 그 계산들이 전부 어긋난다.
--    (오늘 V14 에서 `orders.total_price` 의 의미를 지킨 것과 같은 판단이다.)
--    → 더하는 것은 **정가**(`list_price`)이고, 할인율은 두 값에서 계산한다(저장하지 않는다).
--
-- nullable: 정가가 없으면 **할인 없음**이라는 뜻이다. 기존 상품 5건은 할인한 적이 없으므로
--   NULL 이 사실이고 백필이 필요 없다(V14 배송비의 "0 이 사실"과 같은 성격).
ALTER TABLE product ADD list_price NUMBER(19,0);

-- 주문 품목에도 **정가를 스냅샷**한다.
--
-- 왜 지금 넣나: 나중에 추가하면 **과거 주문은 영영 백필할 수 없다** — 그때 정가가 얼마였는지
-- 알 방법이 없기 때문이다. 배송지(V11)·운송장(V13)에서 이미 겪은 구조다.
-- 상품의 정가를 조회해 쓰면 안 되는 이유도 같다: 상품 가격은 나중에 바뀌므로
-- "그때 얼마에서 얼마로 할인받았는지"는 주문 시점 기록이어야 한다(상품명·가격·이미지와 같은 이유).
--
-- nullable: 할인 없이 산 품목과 정가 도입 이전 주문은 값이 없다 → 화면은 할인 표시를 감춘다.
ALTER TABLE order_item ADD list_price NUMBER(19,0);
