-- 주문 배송비 (2026-07-23)
--
-- 지금까지 total_price는 **상품 합계**뿐이라 커머스 화면인데 금액 구조가 비어 있었다
-- (주문서 결제 요약에 배송비 줄이 없었다).
--
-- ⚠ total_price의 의미는 **바꾸지 않는다.** 여기에 배송비를 더해버리면 이미 쌓인 주문의
-- total_price가 "상품 합계"인지 "결제 금액"인지 알 수 없어진다. 배송비는 별도 컬럼으로 두고,
-- 결제 금액(total_price + shipping_fee)은 응답에서 계산해 내려준다.
--
-- DEFAULT 0 NOT NULL로 한 번에 넣는다:
--   기존 주문은 배송비를 **받은 적이 없으므로 0이 사실**이다(모르는 값이 아니라 0이다).
--   그래서 nullable 추가 → 백필 → NOT NULL 확정(WORKING-AGREEMENTS §2-1)의 3단계가 필요 없다.
--   Oracle 11g+는 DEFAULT가 있는 NOT NULL 컬럼 추가를 메타데이터만 갱신해 처리하므로
--   기존 행을 실제로 갱신하지 않는다(테이블이 커도 빠르다).
--
-- 배송비 **정책**(금액·무료 기준)은 스키마가 아니라 설정(glassvue.shipping)에 있다.
-- 정책은 바뀌지만, 주문에 남는 건 "그 주문에서 실제로 받은 금액"이라 스냅샷이어야 한다
-- — 배송지·구매자 닉네임·상품 이미지와 같은 이유.
ALTER TABLE orders ADD shipping_fee NUMBER(19,0) DEFAULT 0 NOT NULL;
