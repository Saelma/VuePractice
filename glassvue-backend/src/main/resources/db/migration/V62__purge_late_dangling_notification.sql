--
-- ---------------------------------------------------------------- 🔴 왜 또 생겼나
--
-- V61 은 전수 테스트가 앱 컨텍스트를 띄우면서 Flyway 로 적용됐고(09-10 10:36) 55건을 치웠다.
-- **그런데 같은 실행에서 1건이 새로 생겼다.** 경위는 이렇다:
--
--   `ConcurrentDeductionTest` 는 롤백을 안 쓰고 커밋한다 → 재고 0 → `StockRunningLowEvent`
--   → 리스너가 **`@Async`** 라 **다른 스레드**에서 `AFTER_COMMIT` 뒤에 알림을 쓴다.
--   그런데 `@AfterEach` 의 정리는 **그보다 먼저** 돌 수 있다 → 지울 것이 없고,
--   알림은 **그 뒤에** 태어나 고아로 남는다.
--
-- 🔴 **«정리를 넣었다» 와 «정리가 닿았다» 는 다르다.** 비동기가 끼면 순서가 보장되지 않는다.
-- → 그 테스트의 정리를 **예산 2초 폴링**으로 바꿨다(하나라도 지우면 즉시 끝, 없으면 예산만 쓴다).
--   고친 뒤 그 테스트만 다시 돌려 **새로 안 생기는 것**을 확인했다.
--
-- ---------------------------------------------------------------- ⚠ 왜 V61 을 안 고치고 새로 만드나
--
-- V61 은 **이미 적용됐다**(`flyway_schema_history` success=1). 적용된 마이그레이션의 내용을
-- 바꾸면 체크섬이 어긋나 기동이 막힌다. 🔴 **되돌아가서 고치지 않고 앞으로 나아간다.**
--
-- ⚠ 쿼리는 V61 과 같다 — **멱등이라 그래도 안전하다**(지울 것이 없으면 0행).
--   같은 SQL 이 두 번 나오는 것이 중복처럼 보이지만, **각각이 «그 시점의 잔재» 를 치운 기록**이다.

DELETE FROM notification n
 WHERE n.link LIKE '/products/%'
   AND NOT EXISTS (
       SELECT 1 FROM product p
        WHERE p.id = HEXTORAW(REPLACE(REGEXP_SUBSTR(n.link, '[0-9a-f-]{36}$'), '-', ''))
   );
