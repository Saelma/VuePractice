-- 상품 삭제 유예 (2026-08-12, BACKLOG F-7)
--
-- 🔴 **지금 삭제는 하드 삭제였고 되돌릴 수 없었다.** `ProductCommandService.delete` 가 행을 지우면
--   FK ON DELETE CASCADE 로 **옵션(V22)·재고 이력(V39)까지 함께** 사라지고, 이미지 그룹도 지운다.
--   취소 API 는 없다 — 오조작의 대가가 「그 상품에 얽힌 기록 전부」인데 방어는 확인 대화 하나뿐이었다.
--
-- ⚠ **나온 자리**: 2026-08-12 오전에 「(지워진 상품)」 표기를 브라우저에서 검증하다가
--   상품을 지우자 그 리뷰가 이름을 잃는 것을 눈으로 봤고, 사용자가 물었다 —
--   *"사람이 실수로 지울 수도 있잖아?"*
--
-- ---------------------------------------------------------------- 왜 상태가 아니라 시각인가
--
-- ⚠ `ProductStatus` 에 값(«삭제 대기»)을 더하는 안은 **버렸다**(2026-08-12, 사용자 확정):
--   ① enum 값 추가는 Oracle CHECK 제약을 갈아야 한다(`orders.status` 가 2026-07-16 에 ORA-02290 을 냈다).
--   ② 무엇보다 **「숨김」과 뜻이 겹친다** — 숨김은 «계속 팔 생각이 있다», 삭제 대기는 «시한이 있다».
--   🔴 **시한은 상태가 아니라 시각**이라 컬럼이 맞다. `deleted_at` 하나로 «지워졌나» 와
--   «언제까지 되돌릴 수 있나» 가 **둘 다** 나온다(상태 값으로는 뒤엣것을 못 만든다).
--
-- ---------------------------------------------------------------- 컬럼 둘인 이유
--
-- `deleted_by_name` 은 **스냅샷**이다 — 복구 화면이 «누가 지웠나» 를 물어보는데, 그 답을 위해
-- audit 로그를 조인하면 catalog 가 audit 을 조회하게 된다(도메인 경계).
-- ⚠ **주문 취소가 이미 같은 선택을 했다**: `cancelled_by_name`(V40, 2026-08-04) — 관리자가 대신
--   취소한 주문에 «누가» 를 남기려고 이름을 스냅샷했다. 길이도 **같은 50 CHAR** 로 맞춘다
--   (같은 성격의 값이 갈리면 한쪽에서 되던 입력이 다른 쪽에서 ORA-12899 로 터진다, WA §2-2-1).
--
-- ⚠ **`deleted_by`(id)는 두지 않는다.** 지금 이 값을 쓰는 곳은 화면 한 줄뿐이고, id 로 무엇을 더
--   할지 정해지지 않았다. 필요해지면 그때 더한다 — 지어낸 컬럼은 백필이 안 된다.
--
-- ---------------------------------------------------------------- 감사 컬럼은 TZ 를 붙인다
--
-- ⚠ **`TIMESTAMP(9) WITH TIME ZONE`** 이다. plain `TIMESTAMP` 로 만들면 Hibernate validate 는
--   통과하는데 **읽을 때 ORA-18716(시간대가 없다)** 이 난다 — V26 에서 실제로 겪은 사고다.
--   BaseTimeEntity 의 created_at·updated_at 과 같은 타입으로 맞춘다.
--
-- ---------------------------------------------------------------- NULL 의 뜻 · 백필
--
-- ⚠ **NULL = 살아 있는 상품이다.** 이 컬럼이 «삭제 대기» 를 나타내는 유일한 표시이고,
--   조회 갈래들이 전부 `deleted_at IS NULL` 로 거른다.
-- ⚠ **백필하지 않는다** — 이미 하드 삭제된 상품은 행 자체가 없어 되살릴 수 없다.
--   실측(2026-08-12): `product` **6건** · `product_variant` 6 · `stock_history` 23 —
--   전부 살아 있다(삭제 대기 개념이 오늘 생겼다). ⚠ 뒤의 둘을 함께 적는 이유는 **하드 삭제가
--   그것들까지 데려가기 때문**이다(CASCADE). 유예가 지켜 주는 것의 크기가 그 셋이다.
--
-- ⚠ 순수 추가라 구 jar 는 영향받지 않는다(구 jar 는 이 컬럼을 쓰지 않고, 하드 삭제를 계속 한다 —
--   배포 전까지 지워진 상품은 유예 없이 사라지지만 **그건 지금과 같은 동작**이다).

ALTER TABLE product ADD deleted_at TIMESTAMP(9) WITH TIME ZONE;

ALTER TABLE product ADD deleted_by_name VARCHAR2(50 CHAR);

-- 배치가 «유예가 지난 것» 만 고른다: WHERE deleted_at IS NOT NULL AND deleted_at < ?
-- 지금 9건이라 인덱스가 필요 없고, 넣어도 NULL 이 대부분이라 값이 없다 — 필요해지면 그때.

COMMENT ON COLUMN product.deleted_at IS
    '삭제 대기 시각. NULL 이면 살아 있는 상품이다. 유예가 지나면 배치가 진짜로 지운다 (2026-08-12, F-7)';

COMMENT ON COLUMN product.deleted_by_name IS
    '삭제한 관리자 이름(스냅샷). 복구 화면이 「누가 지웠나」에 답하기 위한 값 (2026-08-12, F-7)';
