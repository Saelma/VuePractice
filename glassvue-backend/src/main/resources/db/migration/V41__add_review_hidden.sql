-- 리뷰 숨김 (2026-08-04, 백로그 B-18)
--
-- ⚠ **부적절한 리뷰를 내릴 방법이 없었다.** 리뷰 컨트롤러 전수가 작성자 본인용 넷뿐이고
--   (`POST/GET /products/{id}/reviews` · `PUT/DELETE /reviews/{id}`) **관리자 API 가 0개**다(실측).
--   욕설·광고 리뷰가 올라오면 작성자가 지우기 전까지 아무도 손댈 수 없다.
--
-- ---------------------------------------------------------------- 삭제가 아니라 숨김인 이유
--
-- 되돌릴 수 있어야 한다. 관리자가 잘못 판단할 수 있고, 그때 **원문이 남아 있어야** 되돌린다.
-- 감사 로그(admin_audit_log)가 "누가 숨겼는지" 를 남기지만, 지워진 본문은 로그로도 복구되지 않는다.
--
-- ---------------------------------------------------------------- 숨김이 건드리는 자리는 셋
--
-- ① **목록 조회**(ReviewRepositoryImpl.findByProduct) — 숨긴 것은 안 보인다.
--    ⚠ **작성자 본인에게도 안 보인다**(2026-08-04 결정). 조회 조건이 한 줄로 끝나 어긋나기 어렵다.
--       대가: 작성자는 자기 글이 사라졌다고 느낀다 — CS 로 물어보면 그때 설명한다.
-- ② **별점 집계**(ReviewRepository.statsByProduct) — 숨긴 것은 **빠진다.**
--    안 빼면 *"보이지도 않는 리뷰가 별점을 끌어내리는"* 상태가 된다. 그래서 숨김·해제도
--    ReviewRatingChangedEvent 를 발행해 product.avg_rating·review_count 를 다시 맞춘다.
-- ③ 🔴 **중복 방지**(existsByProductIdAndAuthorId, 상품당 1회) — 숨긴 것도 **그대로 센다.**
--    여기만 반대다. 빼면 **숨기자마자 작성자가 새 리뷰를 쓸 수 있어 숨김이 무의미**해진다.
--    → 같은 컬럼을 세 곳이 다르게 다룬다. 헷갈리기 쉬운 자리라 테스트로 각각 고정한다.
--
-- ---------------------------------------------------------------- 컬럼
--
-- DEFAULT 0 으로 **백필한다** — V37(동의 시각)·V39(재고 이력)·V40(취소 사유)은 백필하지 않았지만
-- 여기는 반대다. 기존 리뷰는 **실제로 숨겨진 적이 없으므로 0 이 사실**이다(V34 email_verified 와 같다).
-- "모르는 값" 이 아니라 "아니다" 라서 NOT NULL 로 둘 수 있고, 그래야 조회 조건에 NULL 갈래가 안 생긴다.
ALTER TABLE review ADD hidden NUMBER(1) DEFAULT 0 NOT NULL;

ALTER TABLE review ADD CONSTRAINT ck_review_hidden CHECK (hidden IN (0, 1));

COMMENT ON COLUMN review.hidden IS
    '관리자 숨김(1=숨김). 목록·별점 집계에서 빠지지만 상품당 1회 제한에는 그대로 센다';

-- 인덱스는 두지 않는다. 유일한 조회 경로가 **상품별 목록**이고 거기엔 이미 조건이 붙는데,
-- hidden 은 값이 둘뿐이라 선택도가 낮아 단독 인덱스가 값을 못 한다.
-- 관리자 목록(전체 리뷰)은 건수가 작고 페이징이 있어 지금은 풀스캔으로 충분하다 —
-- 리뷰가 쌓여 느려지면 그때 (hidden, created_at) 을 본다(H-4 와 같은 판단: 지금은 정상, 도구만 있다).
