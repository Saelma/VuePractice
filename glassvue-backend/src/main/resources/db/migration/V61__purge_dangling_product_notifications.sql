-- 없는 상품을 가리키는 알림을 치운다 (2026-09-10, BACKLOG §M-4).
--
-- ---------------------------------------------------------------- 🔴 무엇이 쌓였나
--
-- 알림의 `link` 는 문자열이고 **FK 가 없다.** 그래서 상품이 사라져도 DB 가 아무것도 안 하고,
-- 「그 상품을 보라」는 줄이 그대로 남는다. 2026-09-10 실측:
--
--   상품을 가리키는 알림  103건  →  그중 가리키는 상품이 없는 것  **55건**
--   고유 상품으로는        16개  →  감사에 남은 것 2개 · 감사에 없는 것 14개
--
-- ⚠ 리뷰·문의·위시리스트·재입고 구독은 **0건**이다(같은 각도로 전부 셌다) — 알림만 그랬다.
--   그것들은 사람이 «실재하는 상품에» 쓴 것이고, 알림은 테스트가 만들었다 지운 상품에도 나갔다.
--
-- ---------------------------------------------------------------- 🔴 두 갈래이고 둘 다 막았다
--
--   ① 테스트 잔재 (14개 상품 · 감사에 흔적 없음)
--      `ConcurrentDeductionTest` 가 롤백을 안 쓰고 커밋해서, 재고 0 → 재고부족 알림이 관리자
--      셋에게 **진짜로** 나갔는데 @AfterEach 는 상품만 지웠다. 매 실행 3건씩(09-02 에만 39건).
--      → 그 테스트의 정리에 알림을 더했다.
--   ② 정상 삭제 (2개 상품 · 감사에 PRODUCT_DELETE 있음)
--      관리자가 지운 상품이다. **이쪽이 진짜 제품 결함**이고 지워도 다음 삭제에서 또 생겼다.
--      → `ProductPurgedEvent` 를 만들어 purge 가 알림을 치우게 했다.
--
-- ⚠ **재발을 먼저 막고 여기서 치운다.** 순서를 뒤집으면 다음 전수에서 또 쌓인다.
--
-- ---------------------------------------------------------------- ⚠ 왜 지우고, 무엇은 안 지우나
--
-- 🔴 갈리는 기준은 **«누가 썼나»** 다. 리뷰·문의는 **사람이 쓴 것**이라 상품이 없어도 읽을 값이
-- 있고 화면이 상품 이름 없음을 이미 견딘다. 알림은 **시스템이 보낸 것**이고 내용이 「가서 보라」
-- 뿐이라, 갈 곳이 없으면 남은 것이 없다. 회원 탈퇴가 알림을 지우는 것(F-1)과 같은 판단이다.
--
-- ⚠ 「링크만 NULL 로 죽이기」도 됐다(화면에 `if (n.link)` 가드가 이미 있다). 안 고른 이유는
--   `Notification.link` 가 `updatable = false` 로 **일부러 불변**이기 때문이다 —
--   「보낸 것은 안 바꾼다」를 한 칸 때문에 깨지 않는다.
--
-- ⚠ 누르면 **크래시가 아니라 막다른 길**이었다(실측): `GET /api/products/<없는 id>` 는 404 이고
--   화면이 그것을 잡아 *"상품을 찾을 수 없습니다"* 를 그린다. 그래서 급한 결함이 아니라 청소로 다뤘다.
--
-- ---------------------------------------------------------------- 되돌리기
--
-- 🔴 **되돌릴 수 없다.** 지우는 행은 이미 «갈 곳이 없는» 알림이고 복구할 값이 없다.
--   ⚠ 그래도 지운 건수를 로그로 남길 수 없으므로(순수 SQL), 위 실측값 55 를 근거로 박아 둔다 —
--   적용 뒤 §M-4 의 불변식 ⑳ 이 0 이 되는 것으로 확인한다.

DELETE FROM notification n
 WHERE n.link LIKE '/products/%'
   AND NOT EXISTS (
       SELECT 1 FROM product p
        WHERE p.id = HEXTORAW(REPLACE(REGEXP_SUBSTR(n.link, '[0-9a-f-]{36}$'), '-', ''))
   );
