-- 반품 거절 사유·시각 (2026-08-11, 08-10 §16-4 4번의 후속)
--
-- ⚠ **알림이 없는 곳을 가리키고 있었다.** 같은 날 붙인 거절 알림이
--   *"자세한 내용은 주문 상세에서 확인해 주세요"* 라고 말하는데, **주문 상세에 아무것도 없었다.**
--   사용자가 브라우저 검증 중에 *"뭘 확인하라는 지 안 나와있어"* 로 지적해 드러났다.
--
-- ---------------------------------------------------------------- 한 겹 더 있었다
--
-- 🔴 거절은 사유가 없는 정도가 아니라 **반품이 있었다는 사실 자체가 화면에서 사라졌다**:
--   ① 거절하면 상태가 `DELIVERED` 로 돌아가는데, 화면의 반품 카드는
--      `RETURN_REQUESTED`·`RETURNED` 일 때만 뜬다 → **카드가 통째로 안 보인다.**
--   ② `Order.rejectReturn()` 이 `return_requested_at` 을 **NULL 로 지운다.**
--   → 결과적으로 «반품을 요청한 적 없는 배송완료 주문» 과 **구분이 안 됐다.**
--
-- ⚠ 그런데 `rejectReturn()` 의 주석은 *"사유는 기록으로 남겨 둔다(요청이 있었다는 흔적)"* 였다 —
--   **의도는 옳았고 동작이 그 의도를 배신했다.** 오늘 §3-1(existsPurchase 의 opt-in 주석)·
--   §15(감사 라벨)와 같은 모양이다: 주석에 적어 둔 약속은 지켜지지 않는다.
--
-- ---------------------------------------------------------------- 왜 컬럼 둘인가
--
-- 취소가 `cancel_reason` + `cancelled_at` 쌍을 갖는 것과 같다(V40). 사유만 있고 시각이 없으면
-- «언제 거절됐나» 를 `updated_at` 으로 추측하게 되는데, 그 값은 다른 변경에도 갱신돼 단정할 수 없다
-- (`cancelled_at` 주석이 이미 같은 말을 한다).
--
-- ⚠ **`return_requested_at` 은 이제 안 지운다**(엔티티 수정). 요청 시각과 거절 시각이 함께 있어야
--   «언제 요청해서 언제 거절됐나» 가 읽힌다. 지우면 그 짝이 반쪽만 남는다.
--
-- ---------------------------------------------------------------- 사유는 필수다
--
-- ⚠ **관리자 취소(B-25)와 같은 판단**이다: 고객은 자기가 왜 요청했는지 알지만,
--   **남이 거절한 이유는 사유가 유일한 단서**다. 그래서 요청(고객)·거절(관리자) 둘 다 필수로 받는다.
--   ⚠ 다만 DB 는 nullable 로 둔다 — 필수는 **요청 DTO** 가 강제한다(관리자 취소 사유와 같은 자리).
--   기존 거절 주문에는 값이 없어 NOT NULL 을 걸 수 없다(아래 백필 참조).
--
-- ---------------------------------------------------------------- NULL 의 뜻 · 백필
--
-- ⚠ **NULL = 거절된 적이 없다.** 거절은 상태를 남기지 않으므로(DELIVERED 로 되돌아간다)
--   이 컬럼이 **«거절이 있었다» 를 나타내는 유일한 표시**가 된다 — 화면도 이걸로 카드를 띄운다.
-- ⚠ **백필하지 않는다.** 과거에 거절된 주문이 있었는지 알 방법이 없다(상태도 시각도 안 남았다).
--   실측(2026-08-11): `RETURNED` 4건 · `RETURN_REQUESTED` 0건 — 거절된 주문은 **식별 자체가 불가능**하다.
--   지어낸 값을 넣으면 «거절당한 적 없는 주문에 거절 이력이 생긴다»(V37·V46 과 같은 판단).
--
-- ⚠ VARCHAR2 는 **문자 단위**로 잡는다(WA §2-2-1). `return_reason`·`cancel_reason` 과 **같은 500 CHAR** —
--   같은 성격의 값이라 갈리면 한쪽에서 되던 입력이 다른 쪽에서 ORA-12899 로 터진다.
--
-- ⚠ 순수 추가라 구 jar 는 영향받지 않는다(구 jar 는 이 컬럼을 쓰지 않는다).

ALTER TABLE orders ADD return_rejected_reason VARCHAR2(500 CHAR);

ALTER TABLE orders ADD return_rejected_at TIMESTAMP(9) WITH TIME ZONE;

COMMENT ON COLUMN orders.return_rejected_reason IS
    '반품 거절 사유(관리자 입력, 필수). NULL 이면 거절된 적이 없다 (2026-08-11)';

COMMENT ON COLUMN orders.return_rejected_at IS
    '반품 거절 시각. updated_at 은 다른 변경에도 갱신돼 대체할 수 없다 (2026-08-11)';
