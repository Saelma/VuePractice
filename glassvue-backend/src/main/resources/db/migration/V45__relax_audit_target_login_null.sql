-- 감사 target_login 을 nullable 로 (2026-08-10, B-18 잔여 작업 중 발견한 결함 보정)
--
-- 🔴 **NOT NULL 이 「탈퇴 회원 대상 조작」을 통째로 막고 있었다.**
--   감사는 대상 loginId 를 스냅샷으로 받는데, 회원이 없으면 조회가 404 라 **조작 자체가 실패**한다.
--   F-1 은 탈퇴 시 **주문과 리뷰를 남기므로**(매출·별점 집계) 그 행이 가리키는 회원은 이미 없을 수 있다:
--     · 탈퇴 회원의 주문을 관리자가 취소  → 404   ⚠ V43/B-25 로 **오늘 아침 배포된 결함**이다
--     · 탈퇴 회원의 리뷰를 숨김           → 404
--   정확히 그 조작이 필요한 상황인데 막혔다.
--
-- ---------------------------------------------------------------- 어떻게 드러났나
--
-- 리뷰 숨김에 감사를 붙이자 **기존 테스트 10건이 404 로 무더기 실패**했다. 그 테스트는 작성자를
-- `UUID.randomUUID()` 로 만들고 있었는데, 처음엔 «인위적인 스텁» 으로 보였다.
-- **아니었다** — F-1 이 리뷰를 남기므로 «작성자가 없는 리뷰» 는 운영의 실제 상태다.
-- ⚠ 스텁이 이상해 보이면 «테스트가 대충 짜였다» 로 넘기기 전에 **그 상태가 운영에 있는지** 본다.
--   (같은 날 오전 B-25 에서는 반대였다 — 그때의 스텁은 운영에서 나올 수 없는 것이라 스텁을 고쳤다.)
--
-- ---------------------------------------------------------------- 처음의 NOT NULL 은 틀린 게 아니었다
--
-- 대상이 «회원 그 자체» 인 조작(정지·역할변경·삭제)만 있을 때는 대상이 반드시 존재했다.
-- 콘텐츠 조치(주문 취소·리뷰 숨김)가 생기며 전제가 깨진 것이다 — **콘텐츠는 작성자보다 오래 산다.**
-- 제약이 잘못 걸렸던 게 아니라, **그 제약이 서 있던 전제가 나중에 무너졌다.**
--
-- ⚠ NULL 은 «조작 시점에 대상 회원이 이미 없었다» 는 **사실**이다. 닉네임이나 '(탈퇴)' 로 메우지 않는다 —
--   그러면 이 열로 조회하는 사람이 **있지도 않은 계정**을 찾게 된다(V37 이 동의 시각을 백필하지 않은 판단).
--
-- ⚠ **제약을 푸는 방향이라 구 jar 는 영향받지 않는다**(구 jar 는 항상 값을 채워 넣는다).
--   반대 방향(NULL → NOT NULL)이었다면 배포 순서를 따져야 했다(WA §5 의 UNIQUE 사고).
--
-- ⚠ **V44 를 고치지 않고 새 버전으로 낸다** — V44 는 12:41 에 이미 적용됐고, 적용된 스크립트를
--   수정하면 체크섬이 어긋나 기동이 통째로 막힌다(실제로 한 번 막혔다: `FlywayValidateException`).

ALTER TABLE admin_audit_log MODIFY (target_login NULL);

COMMENT ON COLUMN admin_audit_log.target_login IS
    '조작 시점 대상 loginId 스냅샷. NULL = 그 시점에 대상 회원이 이미 없었다(탈퇴 회원의 콘텐츠·주문)';
