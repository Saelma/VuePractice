-- 배송지 주소록의 후반부 — 옛 컬럼 정리 (2026-07-24, 백로그 B-5-2)
--
-- V18 이 `member.ship_*` 5컬럼의 값을 `member_address` 로 옮겼고, 같은 커밋에서 **엔티티 매핑을
-- 걷어냈다.** 그래서 지금 이 컬럼들은 **아무도 읽지도 쓰지도 않는** 죽은 컬럼이다.
--
-- ============================================================================
-- 왜 V18 과 같은 파일에 넣지 않았나 (expand / contract)
-- ============================================================================
-- `ddl-auto=validate` 이고, 통합 테스트를 돌리는 순간 Flyway 가 **공유 espdb 에 적용**된다
-- (WORKING-AGREEMENTS §5). V18 에서 같이 DROP 했다면 그 순간 운영에 떠 있던 **구 jar**가
-- 이 컬럼들을 매핑 중이라 **재기동 불가**가 되고 회원 조회가 ORA-00904 로 깨졌을 것이다.
-- 7/21 의 닉네임 UNIQUE(V6) 사고와 같은 종류인데 훨씬 파괴적이다 — UNIQUE 는 신규 가입만
-- 막았지만 컬럼 DROP 은 **이미 되던 조회를 통째로** 깬다.
--
-- → 지금은 안전하다. 착수 전 확인한 것:
--    · 운영 jar 는 V18·V19 를 담은 빌드(10:20)로 교체됐고 정상 동작 중이다.
--    · `Member` 엔티티에 `ship_*` 필드가 없다(주석만 남아 있다).
--    · 네이티브 쿼리·JPQL 어디에도 이 컬럼 참조가 없다.
--      (`Order.ship_recipient` 는 **다른 테이블**의 주문 스냅샷이라 무관하다.)
--
-- ⚠ **되돌릴 수 없다.** 이 스크립트가 돌면 V18 이전 jar 로는 되돌아갈 수 없다.
--    그래도 하는 이유: 남은 값은 이미 **낡은 데이터**다(주소록에서 수정·삭제해도 이쪽은
--    안 따라오므로 실제로 어긋나 있다). 게다가 롤백하면 주소록이 통째로 사라지므로
--    그 경로는 애초에 쓸 수 없다.
--
-- ⚠ `orders.ship_*` 는 **건드리지 않는다.** 주문 시점 스냅샷이고, 주소록과 아무 관계가 없다.
--    이름이 같아서 헷갈리기 쉬운 자리라 한 번 더 적는다.
--
-- 빈 DB 에서는 V11 이 만들고 V12 가 semantics 를 고친 컬럼을 여기서 지우는 순서가 된다 —
-- 중간 버전들이 이 컬럼을 건드리므로 **V11·V12 를 수정하는 게 아니라 뒤에서 지우는 게 맞다**
-- (적용된 마이그레이션은 수정 금지, §2-1).

ALTER TABLE member DROP (
    ship_recipient,
    ship_phone,
    ship_zipcode,
    ship_address1,
    ship_address2
);
