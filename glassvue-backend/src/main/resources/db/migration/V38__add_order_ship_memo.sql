-- 배송 요청사항 (2026-08-03, 백로그 B-20)
--
-- 주문할 때 "부재 시 경비실에" 같은 요청을 남길 자리가 없었다 — OrderCreateRequest 에 배송지
-- 5필드(수령인·전화·우편번호·주소1·2)만 있고 메모가 없다(실측). 실물 배송이 있는 커머스에서
-- 거의 항상 있는 자리다.
--
-- ⚠ **주문 스냅샷이다** — orders.ship_* 5컬럼 옆에 나란히 둔다. 배송지와 같은 성격이라,
--    나중에 주소록(member_address)을 고쳐도 **과거 주문의 메모는 그대로여야** 한다.
--    그래서 member 쪽이 아니라 orders 에 있는 게 맞다(V18 이 배송지를 주소록으로 옮기면서도
--    orders.ship_* 는 건드리지 않은 것과 같은 판단).
--
-- ⚠ **VARCHAR2(200 CHAR)** — 이 DB 의 NLS_LENGTH_SEMANTICS 는 BYTE 라 CHAR 를 안 붙이면
--    200바이트(한글 약 66자)가 된다. V5·V9 가 CHAR 를 빠뜨려 V12 로 보정한 사고가 있었다(WA §2-2-1).
--    200자면 "부재 시 문 앞에 놓아주세요" 류의 요청에 충분하고, 길어질 이유가 없는 자리다.
--
-- nullable 이고 백필하지 않는다 — 기존 주문에는 요청사항이 **없었던 게 사실**이다
-- (V37 의 동의 시각과 같은 판단: 없는 것을 있었던 것처럼 만들지 않는다).
--
-- 순수 추가 + nullable 이라 구 jar 무해(INSERT 가 안 깨진다).

ALTER TABLE orders ADD ship_memo VARCHAR2(200 CHAR);

COMMENT ON COLUMN orders.ship_memo IS
    '배송 요청사항(주문 시점 스냅샷). NULL=요청 없음';
