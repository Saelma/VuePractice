-- 일반 고객센터 문의 (2026-08-07, 백로그 G-3 2단계)
--
-- ⚠ **상품과 무관한 문의를 넣을 곳이 없다.** inquiry.product_id 가 NOT NULL 이라
--   *"배송이 안 와요"*, *"환불 계좌를 바꾸고 싶어요"* 같은 문의를 **할 데가 없었다.**
--   작성 API 도 POST /products/{productId}/inquiries 하나뿐이라 **상품을 고르지 않으면
--   시작조차 안 된다**(실측 2026-08-07).
--
-- 1단계(2026-08-06)가 관리자 **목록**을 열어 *"답할 경로가 없다"* 를 먼저 풀었다.
-- 그래서 지금은 **답할 수 있는데 물어볼 데가 없는** 상태다 — 이 마이그레이션이 그 반대쪽을 연다.
--
-- ---------------------------------------------------------------- 왜 별도 테이블이 아닌가
--
-- 갈래는 둘이었다: ①product_id 를 nullable 로 열기 ②support_ticket 도메인 신설.
-- **①이다.** 관리자 답변 API(POST /api/inquiries/{id}/answer)·답변 알림(B-15)·관리자
-- 목록(1단계)이 **전부 그대로 재사용된다.** ②는 같은 것을 두 번 만드는 것이고, 그러면
-- 관리자가 **두 목록을 번갈아 봐야** 한다 — 1단계에서 방금 없앤 문제가 그대로 돌아온다.
--
-- ---------------------------------------------------------------- ⚠ 상품 문의 목록은 안 건드린다
--
-- InquiryRepositoryImpl.findByProduct 는 productId.eq(...) 라 **NULL 행을 구조적으로 못 잡는다**
-- (SQL 에서 = NULL 은 참이 될 수 없다). 즉 일반 문의가 상품 문의 목록에 섞이지 않는다 —
-- 백로그가 원래 *"product_id is not null 조건이 필요하다"* 고 적어 둔 것은 **틀렸고**,
-- 2026-08-03 실측에서 이미 뒤집혔다. 관리자 목록(1단계)은 NULL 을 **미리 감안해 짜 뒀다**.

-- ---------------------------------------------------------------- ① product_id 를 연다
--
-- ⚠ updatable=false 는 **그대로 둔다**(엔티티). nullable 로 여는 것과 "한 번 정해지면 못 바꾼다" 는
--   다른 이야기다 — 일반 문의를 나중에 상품에 갖다 붙이는 경로는 만들지 않는다(2026-08-07 결정).
--   붙일 수 있게 하면 "이 문의는 어느 상품 것인가" 가 시간에 따라 변해 답변 이력이 어긋난다.
ALTER TABLE inquiry MODIFY (product_id NULL);

COMMENT ON COLUMN inquiry.product_id IS
    '상품 문의면 상품 id(FK 아님, 느슨한 참조). 일반 고객센터 문의면 NULL';

-- ---------------------------------------------------------------- ② 유형 컬럼
--
-- ⚠ **유형이 없으면 관리자가 목록에서 성격을 못 가린다.** 일반 문의는 상품명 열이 비어 있어
--   («상품 없음» 은 «일반 문의» 라는 뜻이지만) 그것만으로는 **배송 문제인지 환불 문제인지**를 모른다.
--   1단계 관리자 목록은 상태(WAITING/ANSWERED)로만 거를 수 있는데, 그건 *"답했나"* 지
--   *"무슨 일인가"* 가 아니다.
--
-- 🔴 **값 집합을 처음에 넉넉히 잡는다 — 이것이 이 마이그레이션에서 가장 되돌리기 비싼 결정이다.**
--   Oracle 에서 enum 값을 나중에 늘리면 ddl-auto=update 가 CHECK 제약을 **못 고쳐** ORA-02290 이
--   나고(이미 데인 자리), 수동 ALTER 가 필요하다. 그래서 화면에 지금 안 쓰는 값도 미리 넣는다:
--     PRODUCT  상품 문의 (기존 경로. 화면에서 고르는 값이 아니라 **경로가 정한다**)
--     DELIVERY 배송
--     REFUND   환불·취소
--     PAYMENT  결제
--     ACCOUNT  회원·계정
--     ETC      기타
--   ⚠ PAYMENT·ACCOUNT 는 **지금 화면에 안 띄운다.** 값을 넣어 두는 비용은 0 이고,
--     빼 뒀다가 나중에 넣는 비용은 수동 ALTER 다 — 비대칭이라 넣는 쪽으로 기운다.
--
-- ⚠ VARCHAR2(n) 는 이 DB 에서 **바이트**다. 반드시 CHAR 를 붙인다(WA §2-2-1).
--   길이는 status(20 CHAR)와 맞춘다 — 같은 성격(enum name 저장)이라 갈릴 이유가 없다.
ALTER TABLE inquiry ADD inquiry_type VARCHAR2(20 CHAR);

-- ---------------------------------------------------------------- ③ 백필 → NOT NULL (순서가 있다)
--
-- ⚠ **순서를 뒤집으면 기존 행 때문에 NOT NULL 이 실패한다**(ORA-02296).
--   그래서 ②는 nullable 로 추가하고, 채운 뒤에, ④에서 조인다.
--
-- 기존 문의는 **전부 상품 문의다**(product_id 가 NOT NULL 이었으므로 구조적으로 그렇다).
-- 즉 PRODUCT 는 **지어낸 값이 아니라 사실**이다 — V40(취소 사유)·V37(동의 시각)을 백필하지 않은
-- 것과 반대인 이유가 여기 있다. 저기는 "모르는 값" 이었고 여기는 "아는 값" 이다.
UPDATE inquiry SET inquiry_type = 'PRODUCT' WHERE inquiry_type IS NULL;

-- ---------------------------------------------------------------- ④ 조인다
ALTER TABLE inquiry MODIFY (inquiry_type NOT NULL);

ALTER TABLE inquiry ADD CONSTRAINT ck_inquiry_type
    CHECK (inquiry_type IN ('PRODUCT', 'DELIVERY', 'REFUND', 'PAYMENT', 'ACCOUNT', 'ETC'));

COMMENT ON COLUMN inquiry.inquiry_type IS
    '문의 유형. PRODUCT 는 상품 문의(경로가 정한다), 나머지는 일반 고객센터 문의';

-- ---------------------------------------------------------------- ⑤ 🔴 둘이 어긋나지 못하게 한다
--
-- product_id 와 inquiry_type 은 **같은 사실을 두 번 적은 것**이다: 상품 문의면 둘 다 채워지고
-- 일반 문의면 둘 다 비어야 한다. 같은 사실이 두 컬럼에 나뉘면 **한쪽만 틀리는** 행이 생긴다:
--   · type=PRODUCT 인데 product_id 가 NULL   → 관리자 목록에서 상품명이 영원히 «—» 인데 유형은 상품 문의
--   · type=DELIVERY 인데 product_id 가 있음   → 그 문의가 상품 문의 목록에 **섞여 뜬다**
-- 둘 다 **앱은 멀쩡히 돌고 화면도 그려진다** — 어제 두 번 나온 「멀쩡해 보이는데 틀린 것」이다.
--
-- 앱에서도 막지만(작성 경로가 둘로 갈린다), 앱 방어는 **경로가 하나 더 생기면 새는** 종류다.
-- 관리자 도구·데이터 보정·다음 기능이 INSERT 를 하나 더 만들면 그 자리는 이 규칙을 모른다.
-- → DB 가 마지막에 잡는다. G-2 의 «환영 쿠폰 한 장» 을 유니크 인덱스로 못 박은 것과 같은 판단이다.
--
-- ⚠ **이름을 붙였다**(ck_inquiry_product_pair). 나중에 «상품을 참조하는 일반 문의» 가 필요해지면
--   DROP CONSTRAINT 한 줄로 푼다 — V1 의 status CHECK 처럼 시스템 이름이면 동적 탐색이 필요하다
--   (V13 이 실제로 그렇게 했다).
ALTER TABLE inquiry ADD CONSTRAINT ck_inquiry_product_pair
    CHECK (
        (inquiry_type = 'PRODUCT' AND product_id IS NOT NULL)
        OR (inquiry_type <> 'PRODUCT' AND product_id IS NULL)
    );

-- ---------------------------------------------------------------- ⑥ 내 문의 목록용 인덱스
--
-- 3단계(내 문의 목록)가 author_id 로 조회한다. 지금까지 author_id 를 쓰는 곳은
-- **탈퇴 정리(F-1)뿐**이라 인덱스가 없었다 — 회원당 한 번 도는 경로라 풀스캔이어도 됐다.
-- 이제 **사용자가 여는 화면**이 되므로 다르다.
--
-- ⚠ 단일 컬럼으로 둔다(idx_inquiry_product 와 같은 모양). (author_id, created_at) 복합도
--   생각했지만, 한 사람이 쓰는 문의는 많아야 수십 건이라 정렬 비용이 무의미하다 —
--   지금 필요 없는 폭을 미리 넣지 않는다(H-4 와 같은 판단: 지금은 정상, 느려지면 그때 본다).
CREATE INDEX idx_inquiry_author ON inquiry (author_id);
