-- 주문 품목에 **세일 전 판매가**를 남긴다 (2026-08-20, BACKLOG G-9)
--
-- 🔴 **세일로 팔린 주문에 «얼마에서 깎였는지» 가 안 남는다.** 실측(2026-08-20, `20260820-4733`):
--   `ZZ-세일검증` L 옵션을 세일가 9,600 에 샀는데 `order_item.list_price` 가 **NULL** 이라
--   **9,600 만 남고 «원래 12,000 이었다» 가 없다.**
--
-- ---------------------------------------------------------------- 왜 list_price 를 재활용하지 않나
--
-- 🔴 **정가와 «세일 전 판매가» 는 다른 것이다.**
--   | 컬럼 | 뜻 | 누가 정하나 |
--   |---|---|---|
--   | `list_price` | «원래 이 값어치» (권장소비자가) | 관리자가 **손으로** 넣는다. 비워 둘 수 있다 |
--   | `regular_price`(신설) | «이 세일이 없었으면 받았을 금액» | **서버가 계산**한다(기본가 + 옵션 가격차) |
--
--   ⚠ 한 칸에 섞으면 어느 쪽인지 못 읽는다. V52 가 «정가와 세일은 다른 것이다» 로 가른 것과 같은 판단이고,
--   실제로 오늘 주문이 그 반례였다 — **정가 칸이 비어 있어서 복사할 것이 없었다.**
--
--   🔴 **V52 주석의 전제가 여기서 깨졌다**: *"주문 쪽은 안전하다 — B-7 이 정가·판매가를 주문에
--   복사한다"* 는 **정가 칸이 채워진 상품에만 성립**한다.
--
-- ---------------------------------------------------------------- 왜 아픈가
--
-- ⚠ 상품이 지워지면 `product_discount` 도 **CASCADE 로 사라진다**(V52 가 의도한 것).
--   그러면 «이 주문은 왜 9,600 이었나» 를 되짚을 근거가 **어디에도 안 남는다.**
--   매출 집계에서도 할인 전후를 못 가른다.
--
-- ---------------------------------------------------------------- 🔴 백필하지 않는다 · NOT NULL 도 아니다
--
-- ⚠ **`regular_price = price` 로 채우고 싶은 유혹이 있다** — 세일 기능(V52)이 2026-08-19 에 생겼으니
--   그전 주문은 전부 세일이 없었고, 그 행들에는 그 값이 **맞다.**
-- 🔴 **그런데 08-19 이후 주문 둘(`20260820-4733`·`4734`)은 실제로 세일가로 나갔다.**
--   거기에 `regular_price = price` 를 쓰면 **«세일이 없었다» 는 거짓을 원장에 적는 것**이 된다.
--   → **전부 NULL 로 둔다.** {@code NULL} 은 «그때는 이 값을 안 남겼다» 는 **사실**이다
--   (V44·V50·V51 의 «모르는 값은 지어내지 않는다» 와 같은 판단).
--
-- ⚠ **그 둘은 계산해서 채울 수도 있다**(할인 행이 아직 살아 있다). 그래도 안 한다 —
--   🔴 **이 기능의 존재 이유가 «할인 행이 사라지면 못 되짚는다» 인데, 백필이 바로 그 취약한 근거에
--   기댄다.** 두 행을 채우려고 원칙을 굽힐 값이 아니다. 대신 **핸드오프에 적어 둔다.**
--
-- ⚠ 순수 추가라 구 jar 는 영향받지 않는다(이 컬럼을 안 읽고, nullable 이라 INSERT 도 안 깨진다).
-- ⚠ `VARCHAR2` 가 아니라 `NUMBER` 라 §2-2-1(CHAR) 은 해당 없다.

ALTER TABLE order_item ADD regular_price NUMBER(19);

COMMENT ON COLUMN order_item.regular_price IS
    '주문 시점 세일 전 판매가(기본가 + 옵션 가격차). 세일 중이 아니었으면 price 와 같다. NULL 은 이 컬럼이 생기기 전(2026-08-20) 주문이다 — 백필하지 않았다 (G-9)';
