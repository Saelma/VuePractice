-- 이메일 소유 인증 여부 (2026-07-29, B-14)
--
-- B-13 으로 이메일 수집을 열었지만 **확인 메일이 없어 저장된 주소는 미검증**이었다.
-- 오타가 있으면 비밀번호 재설정 링크가 **남의 주소로 간다**. 오늘 발송 채널(B-10 완성)이 붙어
-- 확인 메일을 보낼 수 있게 됐으므로 그 결과를 담을 자리를 만든다.
--
-- boolean(NUMBER(1))인 이유는 member.suspended(V30)와 같다 — 상태가 이진이라 enum CHECK 의
-- 제약 교체 비용을 질 이유가 없다. "인증 대기 중"은 **Redis 의 인증번호 존재 여부**로 알 수 있어
-- 별도 상태값이 필요 없다(DB 에는 확정된 결과만 남긴다).
--
-- ⚠ DEFAULT 0 NOT NULL — **기존 회원은 전부 미인증(0)** 으로 백필된다. 이게 사실과 맞다:
--    지금까지 아무도 확인 메일을 받은 적이 없으므로 "인증됨"으로 시작하면 거짓이 된다.
--    순수 추가 + DEFAULT 라 구 jar 무해(V30 과 같은 형태 — INSERT 가 안 깨진다).
--
-- ⚠ **이메일을 바꾸면 이 값은 코드에서 0으로 되돌아간다**(Member.updateEmail). 인증은 "그 주소"에
--    대한 것이지 회원에 대한 게 아니다 — 주소가 바뀌면 인증도 무효다. DB 제약이 아니라 엔티티가 보장한다.

ALTER TABLE member ADD email_verified NUMBER(1) DEFAULT 0 NOT NULL;
