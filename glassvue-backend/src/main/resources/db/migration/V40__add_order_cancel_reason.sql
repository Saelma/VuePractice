-- 주문 취소 사유 (2026-08-04, 백로그 B-17)
--
-- ⚠ **반품에는 사유가 있는데 취소에는 없었다** — 비대칭이다.
--   requestReturn(id, memberId, reason) 인데 cancel(id, memberId) 는 사유를 안 받는다.
--   그래서 관리자가 주문 상세를 열어도 **왜 취소됐는지 알 방법이 없다.**
--
-- 오늘 만든 재고 이력(V39)이 이 구멍을 한 번 더 드러냈다: 재고 원장의 CANCEL 줄은
-- *"재고가 돌아왔다"* 까지만 말하고 **"왜"** 를 못 답한다. 그 줄은 order_id 를 갖고 있으므로
-- 주문에 사유가 있으면 되짚어진다 — **재고 이력에 사유를 복사하지 않는다**(같은 정보를
-- 두 번 적지 않는다는 V39 의 규칙과 같다).
--
-- ---------------------------------------------------------------- 선례를 그대로 따른다
--
-- 길이·semantics·nullable 전부 return_reason(V24)과 **같게** 맞춘다. 두 값은 같은 성격
-- (주문에 남기는 자유 입력 사유)이라, 갈리면 한쪽에서 되던 입력이 다른 쪽에서 ORA-12899 로 터진다
-- (WORKING-AGREEMENTS §2-2-1 — orders.buyer_nickname 이 실제로 그렇게 어긋나 있었다).
--
-- ⚠ VARCHAR2(n) 는 이 DB 에서 **바이트**다. 반드시 CHAR 를 붙인다.
--
-- ---------------------------------------------------------------- 왜 nullable 인가 (두 가지 이유)
--
-- ① **기존 취소 주문은 사유가 없는 게 사실이다.** 백필하지 않는다 — 지어낸 사유는 근거로 쓰이는
--    순간 틀린 결정을 만든다(V37 이 동의 시각을, V39 가 재고 이력을 백필하지 않은 것과 같은 판단).
-- ② **앞으로도 사유는 선택이다**(2026-08-04 착수 결정). 취소는 고객이 빨리 끝내고 싶은 조작이라
--    입력을 강제하면 마찰이 된다 — 반품은 돈이 얽혀 사유가 필수지만 취소는 그전 단계다.
--    → 그래서 화면도 **비워 두고 취소할 수 있어야** 하고, 빈 문자열은 저장하지 않고 NULL 로 남긴다
--      (공백만 적힌 사유는 "사유가 있다"는 거짓 신호가 된다).
--
-- ⚠ 「누가 취소했나」 컬럼은 **두지 않는다.** 착수 실측에서 백로그 전제가 틀린 것이 나왔다 —
--   *"취소는 고객도 관리자도 한다"* 고 적혀 있지만 **관리자 취소 API 는 없다**
--   (/api/admin/orders 는 GET 3개뿐이고, 취소는 findByIdAndMemberId 라 본인 주문만).
--   즉 취소자는 **항상 주문자 본인**이라 컬럼을 두면 늘 같은 값이 들어간다.
--   관리자 취소를 만들 때 그 항목과 함께 추가한다(BACKLOG 에 별도 항목으로 남겼다).
ALTER TABLE orders ADD cancel_reason VARCHAR2(500 CHAR);

COMMENT ON COLUMN orders.cancel_reason IS
    '주문 취소 사유(자유 입력, 선택). 취소자는 항상 주문자 본인이라 행위자 컬럼은 두지 않는다';
