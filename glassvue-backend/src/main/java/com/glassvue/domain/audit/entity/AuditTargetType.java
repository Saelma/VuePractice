package com.glassvue.domain.audit.entity;

/**
 * 감사 원장의 {@code target_id} 가 <b>무엇의 id 인지</b> (2026-08-20, V53).
 *
 * <p>🔴 <b>이벤트로 받지 않는다</b> — {@link AuditAction} 이 스스로 답한다({@code action.targetType()}).
 * 파라미터로 받으면 «action 은 {@code PRODUCT_UPDATE} 인데 targetType 은 {@code MEMBER}» 인 행을
 * 만들 수 있는데, <b>그런 행은 뜻이 없고 만들 수 있게 두면 언젠가 만들어진다.</b>
 *
 * <p>⚠ <b>{@code DISCOUNT} 가 없다.</b> 할인 조작의 대상을 <b>상품</b>으로 잡았기 때문이다 —
 * 할인 id 는 사람에게 의미가 없고, 궁금한 것은 «어느 상품의 세일인가» 다. 대상을 상품으로 잡으면
 * 상품 수정·삭제·할인이 <b>같은 {@code target_id} 로 묶여</b> «이 상품에 무슨 일이 있었나» 를
 * 훑을 수 있다(그건 다른 방법이 없다). V43 이 주문 취소의 대상을 «주문» 이 아니라 «주문자» 로
 * 잡은 것과 같은 결이다.
 */
public enum AuditTargetType {
    /** 대상이 회원. {@code target_login} 이 채워진다(탈퇴했으면 null). */
    MEMBER,
    /** 대상이 상품. 상품 등록·수정·삭제·복구와 <b>기간 할인 조작</b>이 여기다. */
    PRODUCT,
    /** 대상이 쿠폰 <b>정의</b>. 관리자 수동 발급({@code COUPON_ISSUE})은 대상이 «받는 회원» 이라 여기가 아니다. */
    COUPON,
    /**
     * 대상이 카테고리 (2026-08-21, V56 — 감사 확대 4차).
     *
     * <p>🔴 <b>V53 의 틀이 처음으로 «값을 더해» 확장된 자리다.</b> 그전 넷은 전부 기존 셋 중 하나로
     * 들어갔다 — 할인은 상품으로, 주문·리뷰·문의는 회원으로. <b>카테고리는 어디에도 안 들어간다</b>:
     * 회원이 없고, 상품이 아니고(상품을 담는 그릇이지 상품이 아니다), 쿠폰도 아니다.
     *
     * <p>⚠ <b>상품으로 접으려는 유혹이 있는데 접지 않았다.</b> 접으면 {@code target_id} 가 카테고리 id
     * 인데 종류는 «상품» 이라, 「대상 종류=상품」으로 훑을 때 <b>상품 이력 사이에 상품 아닌 행</b>이 섞인다.
     * 대상 종류의 쓸모가 정확히 «회원 아닌 행을 갈라 보는 것» 인데 그걸 스스로 무너뜨린다.
     *
     * <p>⚠ {@code target_login} 은 {@code null} 이고 카테고리명은 {@code detail} 에 넣는다
     * (상품이 이름을 detail 에 넣는 것과 같다 — <b>감사는 대상보다 오래 산다</b>).
     */
    CATEGORY,
    /**
     * 대상이 공지 (2026-08-21, V56 — 감사 확대 4차).
     *
     * <p>⚠ {@link #CATEGORY} 와 같은 이유로 값을 따로 세운다. 공지에는 {@code authorId}(작성 관리자)가
     * 있어 «대상=작성자» 로 접을 수 <b>있지만</b> 접지 않았다 — 리뷰·문의는 <b>고객이 쓴 것을 관리자가
     * 조치</b>해서 «대상=작성자» 가 뜻을 가졌는데, 공지는 <b>관리자가 쓰고 관리자가 고친다.</b>
     * 그러면 actor 와 target 이 <b>거의 늘 같은 사람</b>이라 원장 한 줄이 아무것도 안 가른다.
     */
    NOTICE
}
